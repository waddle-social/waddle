#!/usr/bin/env python3
"""Generate typed JSON commands from the existing native Rust client, without changing its ABI.

Run with --check in CI to detect drift. No protocol logic or XML is generated.
"""
import argparse
import json
import re
import subprocess
from pathlib import Path

HERE = Path(__file__).resolve().parents[1]
FFI = HERE.parent / 'waddle-xmpp-client-ffi' / 'src'


def split_types(value):
    result, depth, start = [], 0, 0
    for index, character in enumerate(value):
        depth += character in '<([{'
        depth -= character in '>)]}'
        if character == ',' and depth == 0:
            result.append(value[start:index].strip())
            start = index + 1
    result.append(value[start:].strip())
    return [item for item in result if item]


def camel(value):
    return ''.join(word.capitalize() for word in value.split('_'))


def methods():
    found = {}
    pattern = re.compile(r'pub async fn (\w+)\s*\((.*?)\)\s*(?:->\s*([^\{]+?))?\s*\{', re.S)
    for path in sorted(FFI.glob('*.rs')):
        for match in pattern.finditer(path.read_text()):
            name, parameters, output = match.groups()
            # The Flutter-only Rust shutdown helper is not a UniFFI/protocol verb.
            if name in ('connect', 'disconnect', 'flutter_disconnect_and_wait'):
                continue
            args = []
            for parameter in split_types(parameters):
                if parameter == '&self':
                    continue
                key, typ = parameter.split(':', 1)
                args.append((key.strip(), re.sub(r'\s+', ' ', typ.strip())))
            found[name] = {'args': args, 'result': re.sub(r'\s+', ' ', (output or '()').strip()), 'local': False}
    found['parse_jid'] = {'args': [('input', 'String')], 'result': 'Option<WaddleJidParts>', 'local': True}
    found['consistent_color_hue'] = {'args': [('input', 'String')], 'result': 'f64', 'local': True}
    return dict(sorted(found.items()))


def binding_type(key, typ):
    if key == 'jid' or key.endswith('_jid') or key.endswith('_jids'):
        return typ.replace('String', 'jid::Jid')
    return typ


def binding_argument(key, typ):
    if binding_type(key, typ) == typ:
        return key
    if typ.startswith('Option<'):
        return key + '.map(|value| value.to_string())'
    if typ.startswith('Vec<'):
        return key + '.into_iter().map(|value| value.to_string()).collect()'
    return key + '.to_string()'


def generate():
    calls = methods()
    foreign = set()
    for call in calls.values():
        for typ in [call['result']] + [typ for _, typ in call['args']]:
            foreign.update(re.findall(r'\bWaddle\w+', typ))
    foreign.discard('WaddleError')
    out = ['// @generated by scripts/generate_dispatch.py; do not edit.',
           '// All protocol operations delegate to the existing tested Rust facade.',
           'use serde::{Deserialize, Serialize};',
           'use waddle_xmpp_client_ffi::{' + ', '.join(sorted(foreign | {'WaddleClient'})) + '};',
           'use crate::error::RuntimeError;',
           'use crate::request::ConnectArgs;',
           '#[derive(Deserialize)]', '#[serde(tag = "method", content = "args", rename_all = "snake_case")]',
           'pub(crate) enum Operation {', 'Connect(ConnectArgs),', 'Disconnect {},']
    for name, call in calls.items():
        fields = ', '.join(key + ': ' + binding_type(key, typ) for key, typ in call['args'])
        out.append(camel(name) + ' {' + fields + '},')
    out.extend(['}', '#[derive(Serialize)]', '#[serde(untagged)]', 'pub(crate) enum Output {',
                'Unit,', 'Timeline(waddle_flutter_timeline::TimelineSnapshot),'])
    for name, call in calls.items():
        typ = call['result']
        if typ.startswith('Result<'):
            typ = split_types(typ[len('Result<'):-1])[0]
        if typ != '()':
            out.append(camel(name) + '(' + typ + '),')
    out.extend(['}', 'impl Operation {', 'pub(crate) async fn dispatch(self, client: &WaddleClient) -> Result<Output, RuntimeError> {', 'match self {',
                'Self::Connect(_) | Self::Disconnect {} => Err(RuntimeError::invalid("Lifecycle command dispatched as a client verb")),'])
    for name, call in calls.items():
        args = ', '.join(key for key, _ in call['args'])
        arguments = ', '.join(binding_argument(key, typ) for key, typ in call['args'])
        expression = ('waddle_xmpp_client_ffi::' + name + '(' + arguments + ')') if call['local'] else ('client.' + name + '(' + arguments + ').await')
        if call['result'].startswith('Result<'):
            expression += '.map_err(RuntimeError::from)?'
        result_type = call['result']
        if result_type == '()' or result_type.startswith('Result<(),'):
            body = '{' + expression + '; Ok(Output::Unit) }'
        else:
            body = 'Ok(Output::' + camel(name) + '(' + expression + '))'
        out.append('Self::' + camel(name) + ' {' + args + '} => ' + body + ',')
    out.extend(['}', '}', 'pub(crate) fn local(&self) -> Option<Output> {', 'match self {'])
    for name, call in calls.items():
        if call['local']:
            args = ', '.join(key for key, _ in call['args'])
            values = ', '.join(key + '.clone()' for key, _ in call['args'])
            out.append('Self::' + camel(name) + ' {' + args + '} => Some(Output::' + camel(name) + '(waddle_xmpp_client_ffi::' + name + '(' + values + '))),')
    out.extend(['_ => None,', '}', '}', '}'])
    schema = {'connect': {'args': {'server_url': 'URL', 'jid': 'BareJid', 'access_token': 'String', 'resource': 'String', 'resumable': 'bool (default false)'}, 'result': '()'},
              'disconnect': {'args': {}, 'result': '()'}}
    schema.update({name: {'args': dict(call['args']), 'result': call['result']} for name, call in calls.items()})
    source = subprocess.run(
        ['rustfmt', '--edition', '2021', '--emit', 'stdout'],
        input='\n'.join(out) + '\n', text=True, capture_output=True, check=True,
    ).stdout
    return source, json.dumps(schema, indent=2) + '\n'


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    source, schema = generate()
    files = {HERE / 'src' / 'generated.rs': source, HERE / 'rpc-schema.json': schema}
    for path, content in files.items():
        if args.check:
            existing = path.read_text() if path.exists() else ''
            equal = existing == content
            if not equal:
                raise SystemExit(f'Generated dispatcher drift: {path}; run {Path(__file__).name}')
        else:
            path.write_text(content)
    print(f'{len(methods()) + 2} typed native RPC methods')


if __name__ == '__main__':
    main()
