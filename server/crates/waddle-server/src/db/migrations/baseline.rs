//! The schema baseline: one migration that builds the whole schema.
//!
//! The baseline is used only by a process that selected it with
//! [`select`], which the binary does when `WADDLE_DB_BASELINE_ACTION` is
//! set. Without a selection [`MigrationRunner::single`] returns the ledgered
//! history and nothing in this module runs.
//!
//! The selection is process-wide because every ledger reader in a process
//! has to agree on the catalog: the runner that applies it, the owner
//! preparations that verify it and the runtime preflight that pins it all
//! build their runner with `MigrationRunner::single()`.
//!
//! - [`BaselineAction::Apply`] makes version 2000 the catalog. An empty
//!   database is built from it, a database already on it is validated, and
//!   a database that still holds the retired history is refused.
//! - [`BaselineAction::Stamp`] additionally records the baseline on a
//!   database that holds the complete retired history: it checks that the
//!   ledger is exactly the retired manifest and that the schema's structure
//!   has the expected fingerprint, then replaces the retired ledger rows
//!   with the baseline row. It runs no DDL.
//!
//! The SQL, the retired manifest and the fingerprints are generated by
//! `server/scripts/schema_baseline.py` from databases the ledgered history
//! built; see `docs/planning/2046-schema-baseline.md`.
//!
//! [`MigrationRunner::single`]: super::MigrationRunner::single

use std::collections::BTreeMap;
use std::sync::OnceLock;

use sha2::{Digest, Sha256};
use thiserror::Error;
use tracing::info;

use super::{migration_checksum, Migration, MigrationLedgerError};
use crate::db::{DatabaseDriver, DatabaseError, Transaction};

/// Ledger version of the baseline. Every retired version is below it.
pub const BASELINE_VERSION: i64 = 2000;
const BASELINE_DESCRIPTION: &str = "schema baseline";

/// Environment variable that selects the baseline for a process.
pub const BASELINE_ACTION_ENV: &str = "WADDLE_DB_BASELINE_ACTION";

const POSTGRES_SQL: &str = include_str!("../../../sql/baseline/postgres.sql");
const SQLITE_SQL: &str = include_str!("../../../sql/baseline/sqlite.sql");
const POSTGRES_FINGERPRINT_SQL: &str =
    include_str!("../../../sql/baseline/postgres.fingerprint.sql");
const POSTGRES_FINGERPRINT: &str = include_str!("../../../sql/baseline/postgres.fingerprint.json");
const SQLITE_FINGERPRINT: &str = include_str!("../../../sql/baseline/sqlite.fingerprint.json");
const POSTGRES_RETIRED_LEDGER: &str =
    include_str!("../../../sql/baseline/postgres.retired-ledger.json");
const SQLITE_RETIRED_LEDGER: &str =
    include_str!("../../../sql/baseline/sqlite.retired-ledger.json");

/// How many differing objects a refusal names.
const REPORTED_DIFFERENCES: usize = 12;

/// What a process does with the schema baseline.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum BaselineAction {
    /// Use the baseline as the migration catalog.
    Apply,
    /// As [`Self::Apply`], and record the baseline on a database that holds
    /// the complete retired history.
    Stamp,
}

/// The value of `WADDLE_DB_BASELINE_ACTION` is not an action.
#[derive(Debug, Clone, PartialEq, Eq, Error)]
#[error("WADDLE_DB_BASELINE_ACTION must be 'apply' or 'stamp'")]
pub struct BaselineActionError;

/// A process selects the baseline once, before it opens a database.
#[derive(Debug, Clone, PartialEq, Eq, Error)]
#[error("the schema baseline was already selected with a different action")]
pub struct BaselineSelectionError;

impl BaselineAction {
    /// Parse the variable's value. Unset selects nothing; a value that is
    /// set must be an action, so a typo cannot fall back to the history.
    pub fn parse(value: Option<&str>) -> Result<Option<Self>, BaselineActionError> {
        match value {
            None => Ok(None),
            Some("apply") => Ok(Some(Self::Apply)),
            Some("stamp") => Ok(Some(Self::Stamp)),
            Some(_) => Err(BaselineActionError),
        }
    }

    /// Read `WADDLE_DB_BASELINE_ACTION`.
    pub fn from_env() -> Result<Option<Self>, BaselineActionError> {
        match std::env::var(BASELINE_ACTION_ENV) {
            Ok(value) => Self::parse(Some(&value)),
            Err(std::env::VarError::NotPresent) => Ok(None),
            Err(std::env::VarError::NotUnicode(_)) => Err(BaselineActionError),
        }
    }
}

static SELECTED: OnceLock<BaselineAction> = OnceLock::new();

/// Make the baseline this process's migration catalog. Call it before the
/// first database is opened. Selecting the same action again is accepted.
fn select(action: BaselineAction) -> Result<(), BaselineSelectionError> {
    if *SELECTED.get_or_init(|| action) == action {
        Ok(())
    } else {
        Err(BaselineSelectionError)
    }
}

/// Select the baseline when `WADDLE_DB_BASELINE_ACTION` asks for it. The
/// error is the message to show the operator.
pub fn select_from_env() -> Result<(), String> {
    match BaselineAction::from_env().map_err(|error| error.to_string())? {
        Some(action) => {
            info!(
                ?action,
                "The schema baseline is this process's migration catalog"
            );
            select(action).map_err(|error| error.to_string())
        }
        None => Ok(()),
    }
}

/// Whether this process selected the baseline.
pub fn is_selected() -> bool {
    selected().is_some()
}

pub(super) fn selected() -> Option<BaselineAction> {
    SELECTED.get().copied()
}

/// The baseline as a catalog entry. Its PostgreSQL SQL is a template; the
/// checksum is of the template, so it does not depend on the schema's name.
pub(super) fn migration() -> Migration {
    Migration {
        version: BASELINE_VERSION,
        description: BASELINE_DESCRIPTION.to_string(),
        sql_sqlite: SQLITE_SQL,
        sql_postgres: POSTGRES_SQL,
    }
}

/// Apply the baseline's SQL in the migration transaction. On PostgreSQL the
/// template's placeholders are replaced by the name of the schema that
/// leads the search path, quoted by the server the three ways the retired
/// owner preparations spelled it.
pub(super) async fn apply(
    tx: &mut Transaction<'_>,
    driver: DatabaseDriver,
    migration: &Migration,
) -> Result<(), DatabaseError> {
    match driver {
        DatabaseDriver::Sqlite => tx.execute_batch(migration.sql_sqlite).await,
        DatabaseDriver::Postgres => {
            let mut rows = tx
                .query(
                    "SELECT pg_catalog.quote_ident(pg_catalog.current_schema()::text), \
                            pg_catalog.quote_literal(pg_catalog.current_schema()::text), \
                            pg_catalog.current_schema()::text",
                    (),
                )
                .await?;
            let row = rows
                .next()
                .await?
                .ok_or(MigrationLedgerError::UnsafeTargetSchema)?;
            let (bare, literal, name): (String, String, String) =
                (row.get(0)?, row.get(1)?, row.get(2)?);
            drop(rows);
            let quoted = format!("\"{}\"", name.replace('"', "\"\""));
            let sql = migration
                .sql_postgres
                .replace("__SCHEMA_QUOTED__", &quoted)
                .replace("__SCHEMA_LITERAL__", &literal)
                .replace("__SCHEMA__", &bare);
            tx.execute_batch(&sql).await
        }
    }
}

/// Bring the ledger to the baseline before the runner validates it.
///
/// A ledger that is empty or holds only versions from the baseline upwards
/// is left alone. A ledger that holds retired versions is refused under
/// [`BaselineAction::Apply`] and stamped under [`BaselineAction::Stamp`].
/// The caller holds the migration transaction and its locks; every refusal
/// is returned before the first write, and the caller rolls back on error.
pub(super) async fn prepare_ledger(
    tx: &mut Transaction<'_>,
    driver: DatabaseDriver,
    ledger_table: &str,
    action: BaselineAction,
) -> Result<(), DatabaseError> {
    let rows = read_ledger(tx, ledger_table).await?;
    let retired = rows.iter().filter(|row| row.0 < BASELINE_VERSION).count();
    if retired == 0 {
        return Ok(());
    }
    if action != BaselineAction::Stamp {
        return Err(MigrationLedgerError::RetiredLedger { versions: retired }.into());
    }
    if let Some(row) = rows.iter().find(|row| row.0 >= BASELINE_VERSION) {
        return Err(MigrationLedgerError::RetiredLedgerMixed { version: row.0 }.into());
    }
    verify_retired_ledger(&rows, driver)?;
    verify_fingerprint(tx, driver).await?;
    if driver == DatabaseDriver::Postgres {
        verify_exclusive(tx).await?;
    }

    let deleted = tx
        .execute(
            &format!("DELETE FROM {ledger_table} WHERE version < ?"),
            crate::db_params![BASELINE_VERSION],
        )
        .await?;
    let baseline = migration();
    let checksum = migration_checksum(&baseline, driver);
    tx.execute(
        &format!("INSERT INTO {ledger_table} (version, description, checksum) VALUES (?, ?, ?)"),
        crate::db_params![BASELINE_VERSION, BASELINE_DESCRIPTION, checksum.as_str()],
    )
    .await?;
    let after = read_ledger(tx, ledger_table).await?;
    let expected = (
        BASELINE_VERSION,
        BASELINE_DESCRIPTION.to_string(),
        Some(checksum),
    );
    if usize::try_from(deleted).ok() != Some(rows.len()) || after != [expected] {
        return Err(MigrationLedgerError::BaselineStampUnverified.into());
    }
    info!(
        retired = rows.len(),
        version = BASELINE_VERSION,
        "Recorded the schema baseline in place of the retired migration ledger"
    );
    Ok(())
}

type LedgerRow = (i64, String, Option<String>);

async fn read_ledger(
    tx: &mut Transaction<'_>,
    ledger_table: &str,
) -> Result<Vec<LedgerRow>, DatabaseError> {
    let mut rows = tx
        .query(
            &format!("SELECT version, description, checksum FROM {ledger_table} ORDER BY version"),
            (),
        )
        .await?;
    let mut ledger = Vec::new();
    while let Some(row) = rows.next().await? {
        ledger.push((row.get(0)?, row.get(1)?, row.get(2)?));
    }
    Ok(ledger)
}

/// The retired history a database must hold, in version order.
fn retired_ledger(
    driver: DatabaseDriver,
) -> Result<Vec<(i64, String, String)>, MigrationLedgerError> {
    let text = match driver {
        DatabaseDriver::Postgres => POSTGRES_RETIRED_LEDGER,
        DatabaseDriver::Sqlite => SQLITE_RETIRED_LEDGER,
    };
    serde_json::from_str(text).map_err(|_| MigrationLedgerError::BaselineArtefactInvalid)
}

fn expected_fingerprint(
    driver: DatabaseDriver,
) -> Result<BTreeMap<String, String>, MigrationLedgerError> {
    let text = match driver {
        DatabaseDriver::Postgres => POSTGRES_FINGERPRINT,
        DatabaseDriver::Sqlite => SQLITE_FINGERPRINT,
    };
    serde_json::from_str(text).map_err(|_| MigrationLedgerError::BaselineArtefactInvalid)
}

/// The ledger must be the retired manifest row for row: nothing missing,
/// nothing extra, every description and checksum equal.
fn verify_retired_ledger(
    rows: &[LedgerRow],
    driver: DatabaseDriver,
) -> Result<(), MigrationLedgerError> {
    let manifest = retired_ledger(driver)?;
    let expected: BTreeMap<i64, (&str, &str)> = manifest
        .iter()
        .map(|(version, description, checksum)| {
            (*version, (description.as_str(), checksum.as_str()))
        })
        .collect();
    let mut seen = BTreeMap::new();
    for (version, description, checksum) in rows {
        let Some((expected_description, expected_checksum)) = expected.get(version) else {
            return Err(MigrationLedgerError::RetiredLedgerUnknownVersion { version: *version });
        };
        if description != expected_description
            || checksum.as_deref() != Some(*expected_checksum)
            || seen.insert(*version, ()).is_some()
        {
            return Err(MigrationLedgerError::RetiredLedgerMismatch { version: *version });
        }
    }
    let missing: Vec<i64> = expected
        .keys()
        .copied()
        .filter(|version| !seen.contains_key(version))
        .collect();
    if missing.is_empty() {
        Ok(())
    } else {
        Err(MigrationLedgerError::RetiredLedgerIncomplete { missing })
    }
}

/// No other client may be connected while the ledger is rewritten: a server
/// built on the retired history would keep serving on a ledger it refuses.
/// Sessions of this login that carry this session's own non-empty
/// application name belong to the same owner run and are not counted.
async fn verify_exclusive(tx: &mut Transaction<'_>) -> Result<(), DatabaseError> {
    let mut rows = tx
        .query(
            "SELECT (SELECT pg_catalog.count(*) FROM pg_catalog.pg_stat_activity activity \
                      WHERE activity.datname = pg_catalog.current_database() \
                        AND activity.pid <> pg_catalog.pg_backend_pid() \
                        AND (activity.backend_type IS NULL \
                          OR activity.backend_type = 'client backend') \
                        AND NOT (activity.usename = session_user \
                          AND activity.application_name <> '' \
                          AND activity.application_name \
                              = pg_catalog.current_setting('application_name'))) \
                  + (SELECT pg_catalog.count(*) FROM pg_catalog.pg_prepared_xacts prepared \
                      WHERE prepared.database = pg_catalog.current_database())",
            (),
        )
        .await?;
    let others: i64 = match rows.next().await? {
        Some(row) => row.get(0)?,
        None => return Err(MigrationLedgerError::UnsafeCatalog.into()),
    };
    if others == 0 {
        Ok(())
    } else {
        Err(MigrationLedgerError::BaselineStampNotExclusive { others }.into())
    }
}

async fn verify_fingerprint(
    tx: &mut Transaction<'_>,
    driver: DatabaseDriver,
) -> Result<(), DatabaseError> {
    let expected = expected_fingerprint(driver)?;
    let found = match driver {
        DatabaseDriver::Postgres => postgres_fingerprint(tx).await?,
        DatabaseDriver::Sqlite => sqlite_fingerprint(tx).await?,
    };
    let mut differences = Vec::new();
    for (key, digest) in &expected {
        match found.get(key) {
            None => differences.push(format!("missing {key}")),
            Some(other) if other != digest => differences.push(format!("changed {key}")),
            Some(_) => {}
        }
    }
    for key in found.keys() {
        if !expected.contains_key(key) {
            differences.push(format!("unexpected {key}"));
        }
    }
    if differences.is_empty() {
        return Ok(());
    }
    let count = differences.len();
    differences.truncate(REPORTED_DIFFERENCES);
    Err(MigrationLedgerError::BaselineCatalogMismatch {
        count,
        first: differences.join(", "),
    }
    .into())
}

/// Run the fingerprint query with the application schema alone on the
/// search path, which is what makes its definitions independent of the
/// connection's settings, and restore the path afterwards.
async fn postgres_fingerprint(
    tx: &mut Transaction<'_>,
) -> Result<BTreeMap<String, String>, DatabaseError> {
    let mut rows = tx
        .query(
            "SELECT pg_catalog.current_schema()::text, \
                    pg_catalog.current_setting('search_path')",
            (),
        )
        .await?;
    let row = rows
        .next()
        .await?
        .ok_or(MigrationLedgerError::UnsafeTargetSchema)?;
    let (schema, search_path): (String, String) = (row.get(0)?, row.get(1)?);
    drop(rows);
    // The query matches the schema's name as a regular expression word, so
    // only a plain lower-case identifier is accepted.
    let plain = schema
        .chars()
        .enumerate()
        .all(|(index, c)| matches!(c, 'a'..='z' | '_') || (index > 0 && c.is_ascii_digit()));
    if schema.is_empty() || !plain {
        return Err(MigrationLedgerError::UnsafeTargetSchema.into());
    }
    set_search_path(tx, &schema).await?;
    let found = async {
        let mut rows = tx.query(POSTGRES_FINGERPRINT_SQL, ()).await?;
        let mut found = BTreeMap::new();
        while let Some(row) = rows.next().await? {
            found.insert(row.get::<String>(0)?, row.get::<String>(1)?);
        }
        Ok::<_, DatabaseError>(found)
    }
    .await;
    set_search_path(tx, &search_path).await?;
    found
}

async fn set_search_path(tx: &mut Transaction<'_>, path: &str) -> Result<(), DatabaseError> {
    let mut rows = tx
        .query(
            "SELECT pg_catalog.set_config('search_path', ?, true)",
            crate::db_params![path],
        )
        .await?;
    rows.next().await?;
    Ok(())
}

async fn sqlite_fingerprint(
    tx: &mut Transaction<'_>,
) -> Result<BTreeMap<String, String>, DatabaseError> {
    let mut rows = tx
        .query(
            "SELECT type, name, sql FROM sqlite_master \
              WHERE name NOT LIKE 'sqlite\\_%' ESCAPE '\\' AND sql IS NOT NULL",
            (),
        )
        .await?;
    let mut found = BTreeMap::new();
    while let Some(row) = rows.next().await? {
        let (kind, name, sql): (String, String, String) = (row.get(0)?, row.get(1)?, row.get(2)?);
        found.insert(
            format!("{kind} {name}"),
            hex::encode(Sha256::digest(normalise_sqlite_sql(&sql).as_bytes())),
        );
    }
    Ok(found)
}

/// Reduce stored SQLite DDL to a form that ignores layout and comments, as
/// `normalise_sqlite_sql` in `server/scripts/schema_catalog.py` does: runs
/// of whitespace outside quoted text become one space, whitespace after `(`
/// and before `)` or `,` is dropped, and comments are removed. `ALTER TABLE
/// ... ADD COLUMN` splices text into the stored statement, so the same
/// table reached two ways differs in layout only.
fn normalise_sqlite_sql(sql: &str) -> String {
    let chars: Vec<char> = sql.chars().collect();
    let mut tokens: Vec<String> = Vec::new();
    fn space(tokens: &mut Vec<String>) {
        if tokens.last().is_some_and(|last| last != " " && last != "(") {
            tokens.push(" ".to_string());
        }
    }
    let mut index = 0;
    while index < chars.len() {
        let c = chars[index];
        if matches!(c, '\'' | '"' | '`') {
            let mut end = index + 1;
            while end < chars.len() {
                if chars[end] == c {
                    if chars.get(end + 1) == Some(&c) {
                        end += 2;
                        continue;
                    }
                    break;
                }
                end += 1;
            }
            let stop = (end + 1).min(chars.len());
            tokens.push(chars[index..stop].iter().collect());
            index = stop;
        } else if c == '[' {
            let stop = chars[index..]
                .iter()
                .position(|&other| other == ']')
                .map_or(chars.len(), |offset| index + offset + 1);
            tokens.push(chars[index..stop].iter().collect());
            index = stop;
        } else if c == '-' && chars.get(index + 1) == Some(&'-') {
            index = chars[index..]
                .iter()
                .position(|&other| other == '\n')
                .map_or(chars.len(), |offset| index + offset);
            space(&mut tokens);
        } else if c == '/' && chars.get(index + 1) == Some(&'*') {
            index = chars[index + 2..]
                .windows(2)
                .position(|pair| pair == ['*', '/'])
                .map_or(chars.len(), |offset| index + 2 + offset + 2);
            space(&mut tokens);
        } else if c.is_whitespace() {
            space(&mut tokens);
            index += 1;
        } else {
            if matches!(c, ')' | ',') {
                while tokens.last().is_some_and(|last| last == " ") {
                    tokens.pop();
                }
            }
            tokens.push(c.to_string());
            index += 1;
        }
    }
    tokens.concat().trim().to_string()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_action_is_unset_or_one_of_two_words() {
        assert_eq!(BaselineAction::parse(None), Ok(None));
        assert_eq!(
            BaselineAction::parse(Some("apply")),
            Ok(Some(BaselineAction::Apply))
        );
        assert_eq!(
            BaselineAction::parse(Some("stamp")),
            Ok(Some(BaselineAction::Stamp))
        );
        for value in ["", "Stamp", "apply ", "true"] {
            assert_eq!(BaselineAction::parse(Some(value)), Err(BaselineActionError));
        }
    }

    #[test]
    fn the_embedded_artefacts_parse_and_agree() {
        for driver in [DatabaseDriver::Postgres, DatabaseDriver::Sqlite] {
            let ledger = retired_ledger(driver).expect("retired ledger");
            assert!(!ledger.is_empty());
            assert!(ledger.windows(2).all(|pair| pair[0].0 < pair[1].0));
            assert!(ledger
                .iter()
                .all(|(version, _, _)| *version < BASELINE_VERSION));
            assert!(!expected_fingerprint(driver)
                .expect("fingerprint")
                .is_empty());
        }
        let postgres: Vec<i64> = retired_ledger(DatabaseDriver::Postgres)
            .expect("postgres")
            .iter()
            .map(|row| row.0)
            .collect();
        let sqlite: Vec<i64> = retired_ledger(DatabaseDriver::Sqlite)
            .expect("sqlite")
            .iter()
            .map(|row| row.0)
            .collect();
        assert_eq!(postgres, sqlite);
    }

    #[test]
    fn a_retired_ledger_must_equal_the_manifest() {
        let driver = DatabaseDriver::Sqlite;
        let complete: Vec<LedgerRow> = retired_ledger(driver)
            .expect("manifest")
            .into_iter()
            .map(|(version, description, checksum)| (version, description, Some(checksum)))
            .collect();
        assert_eq!(verify_retired_ledger(&complete, driver), Ok(()));

        let mut prefix = complete.clone();
        let last = prefix.pop().expect("a last version");
        assert_eq!(
            verify_retired_ledger(&prefix, driver),
            Err(MigrationLedgerError::RetiredLedgerIncomplete {
                missing: vec![last.0]
            })
        );

        let mut changed = complete.clone();
        changed[0].2 = Some("0".repeat(64));
        assert_eq!(
            verify_retired_ledger(&changed, driver),
            Err(MigrationLedgerError::RetiredLedgerMismatch {
                version: changed[0].0
            })
        );

        let mut unchecked = complete.clone();
        unchecked[0].2 = None;
        assert_eq!(
            verify_retired_ledger(&unchecked, driver),
            Err(MigrationLedgerError::RetiredLedgerMismatch {
                version: unchecked[0].0
            })
        );

        let mut extra = complete;
        extra.push((1999, "unknown".to_string(), None));
        assert_eq!(
            verify_retired_ledger(&extra, driver),
            Err(MigrationLedgerError::RetiredLedgerUnknownVersion { version: 1999 })
        );
    }

    #[test]
    fn sqlite_ddl_is_normalised_as_the_tooling_normalises_it() {
        // The same vector as `test_schema_catalog.py`.
        assert_eq!(
            normalise_sqlite_sql(
                "CREATE TABLE t (\n  a TEXT DEFAULT 'x  --  y' , -- note\n  \"b  c\" INT /* gone */\n)"
            ),
            "CREATE TABLE t (a TEXT DEFAULT 'x  --  y', \"b  c\" INT)"
        );
        assert_eq!(
            normalise_sqlite_sql("CREATE INDEX i ON t ( a ,b )  WHERE a = '('"),
            "CREATE INDEX i ON t (a,b) WHERE a = '('"
        );
    }

    #[test]
    fn the_baseline_checksum_does_not_depend_on_the_schema() {
        let baseline = migration();
        assert_eq!(baseline.version, BASELINE_VERSION);
        assert!(baseline.sql_postgres.contains("__SCHEMA"));
        assert_eq!(
            migration_checksum(&baseline, DatabaseDriver::Postgres),
            hex::encode(Sha256::digest(POSTGRES_SQL.as_bytes()))
        );
    }
}
