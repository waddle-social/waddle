#!/usr/bin/env python3
"""Contract tests for the candidate baseline generator and its round trip.

The SQLite cases always run. The PostgreSQL cases run under the conditions
`test_schema_catalog.py` states, and are skipped otherwise.
"""
import importlib.util
from pathlib import Path
import sys
import tempfile
import unittest

SCRIPTS = Path(__file__).resolve().parent
sys.path.insert(0, str(SCRIPTS))


def _load(name):
    spec = importlib.util.spec_from_file_location(name, SCRIPTS / f"{name}.py")
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


fixtures = _load("test_schema_catalog")
catalog = fixtures.catalog
baseline = _load("schema_baseline")
SQLITE_DIRECT = fixtures.SQLITE_DIRECT
SQLITE_MIGRATED = fixtures.SQLITE_MIGRATED
sqlite_document = fixtures.sqlite_document


class SqliteBaselineTests(unittest.TestCase):
    def setUp(self):
        self.directory = tempfile.TemporaryDirectory()
        self.addCleanup(self.directory.cleanup)

    def test_generated_candidate_round_trips_and_is_deterministic(self):
        document = sqlite_document(self.directory.name, "source.db", SQLITE_MIGRATED)
        result = baseline.generate(document, "public", "abc123", "source.json")
        again = baseline.generate(document, "public", "abc123", "source.json")
        self.assertEqual(result["files"], again["files"])
        self.assertEqual(set(result["files"]), {"sqlite.sql", "sqlite.ledger.sql"})
        self.assertIn("_migrations", result["files"]["sqlite.ledger.sql"])
        self.assertNotIn("_migrations", result["files"]["sqlite.sql"])
        for text in result["files"].values():
            self.assertTrue(text.startswith("-- GENERATED by server/scripts/schema_baseline.py"))
            self.assertIn("-- Source commit: abc123", text)
            self.assertIn("The server does not read it", text)
        out = Path(self.directory.name) / "candidate"
        out.mkdir()
        for name, text in result["files"].items():
            (out / name).write_text(text, encoding="utf-8")
        candidate = baseline.round_trip_sqlite(out)
        self.assertEqual(catalog.compare(document, candidate), [])

    def test_a_hand_edited_candidate_fails_the_round_trip(self):
        document = sqlite_document(self.directory.name, "source.db", SQLITE_DIRECT)
        result = baseline.generate(document, "public", "abc123", "source.json")
        out = Path(self.directory.name) / "candidate"
        out.mkdir()
        for name, text in result["files"].items():
            (out / name).write_text(
                text.replace("WHERE role = 'owner'", "WHERE role = 'member'"), encoding="utf-8")
        candidate = baseline.round_trip_sqlite(out)
        self.assertTrue(catalog.compare(document, candidate))


class GeneratorTests(unittest.TestCase):
    def test_identifiers_are_quoted_only_when_needed(self):
        self.assertEqual(baseline.ident("rooms"), "rooms")
        self.assertEqual(baseline.ident("user"), '"user"')
        self.assertEqual(baseline.ident("Mixed"), '"Mixed"')

    def test_lockstep_reports_unlisted_and_stale_differences(self):
        def table(name):
            return {"schema": "public", "name": name}

        def column(relation, name):
            return {"schema": "public", "relation": relation, "name": name}

        postgres = {"engine": "postgresql", "objects": {
            "table public.a": table("a"), "table public.pg": table("pg"),
            "column public.a.x": column("a", "x"), "column public.a.y": column("a", "y"),
            "index public.i": {"schema": "public", "relation": "a", "name": "i", "constraint": None},
        }}
        sqlite_side = {"engine": "sqlite", "objects": {
            "table a": {"name": "a"}, "column a.x": {"relation": "a", "name": "x"},
        }}
        allowed = {"postgres-only": {"gone"}, "sqlite-only": set()}
        self.assertEqual(
            baseline.lockstep(postgres, sqlite_side, "public", allowed),
            ["postgres-only table pg is not listed",
             "postgres-only listing gone no longer applies",
             "postgres-only column a.y",
             "postgres-only index a.i"],
        )

    def test_the_committed_engine_differences_parse(self):
        allowed = baseline.read_engine_differences(SCRIPTS / "schema-engine-differences.txt")
        self.assertIn("clustering_claims", allowed["postgres-only"])
        self.assertIn("pending_notification_recovery_counter", allowed["sqlite-only"])



class PostgresBaselineTests(fixtures.PostgresFixture):
    def test_generated_candidate_round_trips_including_privileges(self):
        result = baseline.generate(self.migrated, "public", "abc123", "source.json")
        self.assertEqual(result, baseline.generate(self.direct, "public", "abc123", "source.json"))
        structure = result["files"]["postgres.sql"]
        self.assertNotIn(self.owner, structure)
        self.assertNotIn("public.", structure)
        self.assertEqual(result["names"], [])
        with tempfile.TemporaryDirectory() as directory:
            for name, text in result["files"].items():
                (Path(directory) / name).write_text(text, encoding="utf-8")
            candidate = baseline.round_trip_postgres(
                Path(directory), self.admin_url, self.psql, "public")
        self.assertEqual(catalog.compare(self.migrated, candidate), [])
        leftover = catalog.run_psql(
            self.psql, self.admin_url,
            "SELECT datname FROM pg_catalog.pg_database "
            f"WHERE datname LIKE '{baseline.ROUND_TRIP_PREFIX}%'")
        self.assertEqual(leftover.strip(), "")

    def test_an_object_the_generator_cannot_reproduce_is_refused_by_name(self):
        document = self.build(
            "unsupported",
            "CREATE TABLE t (a int); CREATE MATERIALIZED VIEW m AS SELECT a FROM t;"
            "ALTER TABLE t ENABLE ROW LEVEL SECURITY;",
        )
        with self.assertRaises(baseline.Unsupported) as refused:
            baseline.generate(document, "public", "abc123", "source.json")
        message = str(refused.exception)
        self.assertIn("materialized_view m", message)
        self.assertIn("table t: row_security", message)


if __name__ == "__main__":
    unittest.main()
